"""Nexus IT Pack: Squad Orchestrator connecting BA, SA, DA, UI/UX, Full-Stack, DevOps, and QA."""

from __future__ import annotations

import logging
from pathlib import Path

from pydantic import BaseModel

from nexus.dashboard.telemetry import AgentEvent, EventType, event_bus
from nexus.providers.base import BaseModelProvider
from nexus.providers.vertex import VertexAIProvider
from nexus.teams.it_pack.ba import BusinessAnalystAgent, ProductProposal
from nexus.teams.it_pack.data_architect import DataArchitectAgent, DataArchitecture
from nexus.teams.it_pack.designer import UiDesignerAgent, UiSpecification
from nexus.teams.it_pack.devops import DevopsEngineerAgent, DevopsSpecification
from nexus.teams.it_pack.fullstack import FullStackEngineerAgent, FullStackSpecification
from nexus.teams.it_pack.qa import QaEngineerAgent, QaSpecification
from nexus.teams.it_pack.solution_architect import (
    SolutionArchitectAgent,
    SolutionBlueprint,
)

logger = logging.getLogger("nexus.teams.it_pack")


class DeliveredProject(BaseModel):
    """The complete software package generated by the Nexus IT Team."""

    proposal: ProductProposal
    solution: SolutionBlueprint
    data_architecture: DataArchitecture
    ui: UiSpecification
    fullstack: FullStackSpecification
    devops: DevopsSpecification
    qa: QaSpecification
    output_path: str | None = None


class NexusITTeam:
    """
    Virtual IT Team of Autonomous Subagents:
    - Business Analyst
    - Solution Architect
    - Data Architect
    - UI/UX Designer
    - Full-Stack Engineer
    - DevOps Engineer (Terraform / IaC)
    - QA & Security Engineer
    """

    def __init__(self, provider: BaseModelProvider | None = None) -> None:
        self.provider = provider or VertexAIProvider()
        self.ba = BusinessAnalystAgent(self.provider)
        self.solution_architect = SolutionArchitectAgent(self.provider)
        self.data_architect = DataArchitectAgent(self.provider)
        self.designer = UiDesignerAgent(self.provider)
        self.fullstack = FullStackEngineerAgent(self.provider)
        self.devops = DevopsEngineerAgent(self.provider)
        self.qa = QaEngineerAgent(self.provider)

    def build_from_idea(
        self,
        raw_user_idea: str,
        target_cloud: str = "gcp",
        output_dir: Path | None = None,
    ) -> DeliveredProject:
        """Run the end-to-end squad workflow from idea to deployed architecture."""
        # 1. Business Analyst
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Business Analyst",
                f"Analyzing requirements for: '{raw_user_idea[:60]}...'",
            )
        )
        proposal = self.ba.analyze_requirements(raw_user_idea)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Business Analyst",
                f"Proposal compiled: {proposal.title}",
                {"snippet": proposal.tagline},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Business Analyst",
                f"Delivered {len(proposal.user_stories)} user stories.",
            )
        )

        # 2. Solution Architect
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Solution Architect",
                f"Evaluating system topology and cloud strategy for {target_cloud.upper()}...",
            )
        )
        solution = self.solution_architect.design_solution(proposal, target_cloud=target_cloud)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Solution Architect",
                f"Architecture Blueprint ready ({solution.compute_pattern})",
                {"snippet": solution.system_topology},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Solution Architect",
                f"Target cloud: {solution.cloud_provider.upper()}, services: {len(solution.integration_services)}",
            )
        )

        # 3. Data Architect
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Data Architect",
                f"Designing normalized relational schema & DDL for {proposal.title}...",
            )
        )
        data_arch = self.data_architect.design_data_model(proposal, solution)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Data Architect",
                f"Data Architecture locked ({len(data_arch.tables)} tables)",
                {"snippet": data_arch.database_engine},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Data Architect",
                f"Generated SQL DDL schema with {len(data_arch.indexes)} indexes.",
            )
        )

        # 4. UI/UX Designer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "UI/UX Designer",
                f"Crafting user journey, design tokens & wireframes for {proposal.title}...",
            )
        )
        ui = self.designer.design_ui(proposal, solution)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "UI/UX Designer",
                f"UI mockup ready: {ui.component_name}",
                {"snippet": ui.color_palette},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "UI/UX Designer",
                "UI tokens and visual mockup ready.",
            )
        )

        # 5. Full-Stack Engineer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Full-Stack Engineer",
                "Implementing unified React frontend + FastAPI backend...",
            )
        )
        fullstack = self.fullstack.build_application(proposal, solution, data_arch, ui)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Full-Stack Engineer",
                "Full-Stack codebase compiled",
                {"snippet": fullstack.backend_main_py[:120]},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Full-Stack Engineer",
                "React interface + FastAPI microservice integrated.",
            )
        )

        # 6. DevOps Engineer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "DevOps Engineer",
                f"Generating Terraform (IaC) and container config for {solution.cloud_provider.upper()}...",
            )
        )
        devops = self.devops.build_infrastructure(proposal, solution)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "DevOps Engineer",
                f"Terraform IaC compiled ({solution.cloud_provider})",
                {"snippet": devops.terraform_main_tf[:120]},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "DevOps Engineer",
                "Terraform modules, Dockerfile & CI/CD workflow ready.",
            )
        )

        # 7. QA & Security Engineer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "QA & Security Engineer",
                "Executing preflight security check & generating test suite...",
            )
        )
        qa = self.qa.verify_and_test(proposal, solution, fullstack)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "QA & Security Engineer",
                "Automated pytest suite compiled",
                {"snippet": qa.test_suite_code[:120]},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "QA & Security Engineer",
                f"Preflight clearance: {'PASSED' if qa.passed_preflight else 'WARN'}",
            )
        )

        saved_path = None
        if output_dir:
            app_dir = output_dir / proposal.app_name
            saved_path = str(self._write_to_disk(app_dir, proposal, solution, data_arch, ui, fullstack, devops, qa))
            event_bus.emit(
                AgentEvent(
                    EventType.RUN_COMPLETED,
                    "Squad Orchestrator",
                    f"Project delivered to disk at {saved_path}",
                )
            )
        else:
            event_bus.emit(
                AgentEvent(
                    EventType.RUN_COMPLETED,
                    "Squad Orchestrator",
                    "Project delivery complete.",
                )
            )

        return DeliveredProject(
            proposal=proposal,
            solution=solution,
            data_architecture=data_arch,
            ui=ui,
            fullstack=fullstack,
            devops=devops,
            qa=qa,
            output_path=saved_path,
        )

    @staticmethod
    @staticmethod
    def _sanitize_python(code: str) -> str:
        """Ensure Python code is syntactically valid and repair common LLM syntax/MRO patterns."""
        import ast
        import re

        # Normalize redundant Base in MRO: class Foo(Base, NexusEntity) -> class Foo(NexusEntity)
        code = re.sub(
            r"class\s+([A-Za-z0-9_]+)\s*\(\s*Base\s*,\s*NexusEntity\s*\):",
            r"class \1(NexusEntity):",
            code,
        )

        try:
            ast.parse(code)
            return code
        except SyntaxError:

            def fix_fstring(m: re.Match[str]) -> str:
                inner = m.group(1)
                if r"\"" in inner or r"\'" in inner or "{" in inner:
                    return f'"{inner}"'
                return m.group(0)

            sanitized = re.sub(r'f"([^"]+)"', fix_fstring, code)
            try:
                ast.parse(sanitized)
                return sanitized
            except SyntaxError:
                return code

    def _write_to_disk(
        self,
        app_dir: Path,
        proposal: ProductProposal,
        solution: SolutionBlueprint,
        data_arch: DataArchitecture,
        ui: UiSpecification,
        fullstack: FullStackSpecification,
        devops: DevopsSpecification,
        qa: QaSpecification,
    ) -> Path:
        """Write all generated artifacts into a runnable workspace."""
        backend_dir = app_dir / "backend" / "src"
        test_dir = app_dir / "backend" / "tests"
        frontend_dir = app_dir / "frontend" / "src"
        infra_dir = app_dir / "infra" / "terraform"
        docs_dir = app_dir / "docs"
        github_dir = app_dir / ".github" / "workflows"

        for d in (backend_dir, test_dir, frontend_dir, infra_dir, docs_dir, github_dir):
            d.mkdir(parents=True, exist_ok=True)

        # 1. Documentation
        (docs_dir / "PROPOSAL.md").write_text(
            f"# {proposal.title}\n\n> {proposal.tagline}\n\n## User Stories\n"
            + "\n".join(f"- {s}" for s in proposal.user_stories),
            encoding="utf-8",
        )
        (docs_dir / "ARCHITECTURE.md").write_text(
            f"# System Architecture Blueprint\n\n- Cloud Target: {solution.cloud_provider}\n- Compute: {solution.compute_pattern}\n\n## Topology\n{solution.system_topology}",
            encoding="utf-8",
        )
        (docs_dir / "DATA_ARCHITECTURE.md").write_text(
            f"# Data Architecture\n\nEngine: {data_arch.database_engine}\n\n## Tables\n"
            + "\n".join(f"- {t}" for t in data_arch.tables)
            + f"\n\n## SQL Schema\n```sql\n{data_arch.sql_ddl_schema}\n```",
            encoding="utf-8",
        )
        (docs_dir / "preview_mockup.html").write_text(proposal.wireframe_preview_html, encoding="utf-8")

        # 2. Frontend
        (frontend_dir / "App.tsx").write_text(fullstack.frontend_app_tsx, encoding="utf-8")
        (frontend_dir / "api.ts").write_text(fullstack.frontend_api_client_ts, encoding="utf-8")
        frontend_pkg = f"""{{
  "name": "{proposal.app_name}-web",
  "version": "0.1.0",
  "private": true,
  "type": "module",
  "scripts": {{
    "dev": "vite",
    "build": "tsc && vite build",
    "preview": "vite preview"
  }},
  "dependencies": {{
    "@nexus/ui": "workspace:*",
    "@nexus/contracts": "workspace:*",
    "react": "^18.3.1",
    "react-dom": "^18.3.1"
  }},
  "devDependencies": {{
    "@types/react": "^18.3.3",
    "@types/react-dom": "^18.3.0",
    "tailwindcss": "^3.4.4",
    "typescript": "^5.4.5",
    "vite": "^5.3.1"
  }}
}}
"""
        (app_dir / "frontend" / "package.json").write_text(frontend_pkg, encoding="utf-8")

        # 3. Backend
        (backend_dir / "main.py").write_text(self._sanitize_python(fullstack.backend_main_py), encoding="utf-8")
        sanitized_models = self._sanitize_python(fullstack.backend_models_py)
        (backend_dir / "models.py").write_text(sanitized_models, encoding="utf-8")
        (backend_dir / "backend_models.py").write_text(sanitized_models, encoding="utf-8")
        (backend_dir / "__init__.py").write_text("", encoding="utf-8")

        # 4. Tests
        (test_dir / "test_api.py").write_text(self._sanitize_python(qa.test_suite_code), encoding="utf-8")
        (test_dir / "__init__.py").write_text("", encoding="utf-8")

        # 5. Infrastructure as Code (Terraform)
        (infra_dir / "main.tf").write_text(devops.terraform_main_tf, encoding="utf-8")
        (infra_dir / "variables.tf").write_text(devops.terraform_variables_tf, encoding="utf-8")
        (app_dir / "docker-compose.yml").write_text(devops.docker_compose_yml, encoding="utf-8")
        (github_dir / "deploy.yml").write_text(devops.ci_cd_workflow_yml, encoding="utf-8")

        # 6. pyproject.toml
        pyproject_content = f"""[project]
name = "{proposal.app_name}"
version = "0.1.0"
description = "{proposal.title} powered by Nexus Platform Framework"
requires-python = ">=3.11"
dependencies = [
    "nexus-framework>=0.1.0",
    "uvicorn>=0.30.0",
]

[project.optional-dependencies]
dev = [
    "pytest>=8.0.0",
    "pytest-asyncio>=0.23.0",
    "httpx>=0.27.0",
]

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.pytest.ini_options]
pythonpath = ["src"]
asyncio_mode = "auto"
"""
        (app_dir / "backend" / "pyproject.toml").write_text(pyproject_content, encoding="utf-8")

        return app_dir
