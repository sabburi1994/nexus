"""Nexus IT Pack: Squad Orchestrator connecting BA, Manager, Designer, Engineer, and QA."""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any
from pydantic import BaseModel

from nexus.providers.base import BaseModelProvider
from nexus.providers.vertex import VertexAIProvider
from nexus.teams.it_pack.ba import BusinessAnalystAgent, ProductProposal
from nexus.teams.it_pack.designer import UiDesignerAgent, UiSpecification
from nexus.teams.it_pack.engineer import BackendEngineerAgent, BackendSpecification
from nexus.teams.it_pack.manager import EngineeringManagerAgent, SprintPlan
from nexus.teams.it_pack.qa import QaEngineerAgent, QaSpecification

logger = logging.getLogger("nexus.teams.it_pack")


class DeliveredProject(BaseModel):
    """The complete software package generated by the Nexus IT Team."""
    proposal: ProductProposal
    sprint_plan: SprintPlan
    ui: UiSpecification
    backend: BackendSpecification
    qa: QaSpecification
    output_path: str | None = None


class NexusITTeam:
    """
    Virtual IT Team of Autonomous Subagents.
    Transforms raw, unrefined user requirements into a complete, working software project.
    """

    def __init__(self, provider: BaseModelProvider | None = None) -> None:
        self.provider = provider or VertexAIProvider()
        self.ba = BusinessAnalystAgent(self.provider)
        self.manager = EngineeringManagerAgent(self.provider)
        self.designer = UiDesignerAgent(self.provider)
        self.engineer = BackendEngineerAgent(self.provider)
        self.qa = QaEngineerAgent(self.provider)

    def build_from_idea(
        self,
        raw_user_idea: str,
        output_dir: Path | None = None,
    ) -> DeliveredProject:
        """Run the end-to-end squad workflow from idea to tested codebase."""
        logger.info("1/5: Business Analyst formulating proposal...")
        proposal = self.ba.analyze_requirements(raw_user_idea)

        logger.info("2/5: Engineering Manager breaking down sprint plan...")
        plan = self.manager.plan_sprint(proposal)

        logger.info("3/5: UI/UX Designer crafting React component...")
        ui = self.designer.design_ui(proposal, plan)

        logger.info("4/5: Backend Engineer implementing FastAPI service...")
        backend = self.engineer.build_backend(proposal, plan)

        logger.info("5/5: QA & Security Engineer generating test suite...")
        qa = self.qa.verify_and_test(proposal, plan)

        saved_path = None
        if output_dir:
            app_dir = output_dir / proposal.app_name
            saved_path = str(self._write_to_disk(app_dir, proposal, plan, ui, backend, qa))

        return DeliveredProject(
            proposal=proposal,
            sprint_plan=plan,
            ui=ui,
            backend=backend,
            qa=qa,
            output_path=saved_path,
        )

    @staticmethod
    def _write_to_disk(
        app_dir: Path,
        proposal: ProductProposal,
        plan: SprintPlan,
        ui: UiSpecification,
        backend: BackendSpecification,
        qa: QaSpecification,
    ) -> Path:
        """Write all generated artifacts into a runnable workspace."""
        backend_dir = app_dir / "backend" / "src"
        test_dir = app_dir / "backend" / "tests"
        frontend_dir = app_dir / "frontend" / "src"
        docs_dir = app_dir / "docs"

        for d in (backend_dir, test_dir, frontend_dir, docs_dir):
            d.mkdir(parents=True, exist_ok=True)

        # 1. Documentation
        proposal_md = f"""# {proposal.title}

> {proposal.tagline}

## User Stories
{chr(10).join(f"- {s}" for s in proposal.user_stories)}

## Core Features
{chr(10).join(f"- {f}" for f in proposal.core_features)}

## UI/UX Wireframe Concept
{proposal.ui_concept}
"""
        (docs_dir / "PROPOSAL.md").write_text(proposal_md, encoding="utf-8")
        (docs_dir / "preview_mockup.html").write_text(proposal.wireframe_preview_html, encoding="utf-8")

        # 2. Sprint Plan
        plan_md = f"""# Sprint Plan & Architecture

## Architecture
{plan.architecture_overview}

## Database Entities
{chr(10).join(f"- {e}" for e in plan.database_entities)}

## REST API Endpoints
{chr(10).join(f"- {ep}" for ep in plan.api_endpoints)}

## Engineering Tasks
{chr(10).join(f"- [{t.assignee}] {t.task_id}: {t.title} - {t.description}" for t in plan.tasks)}
"""
        (docs_dir / "SPRINT_PLAN.md").write_text(plan_md, encoding="utf-8")

        # 3. Frontend UI Component
        (frontend_dir / f"{ui.component_name}.tsx").write_text(ui.react_code, encoding="utf-8")

        # 4. Backend Service
        (backend_dir / "main.py").write_text(backend.entry_point_code, encoding="utf-8")
        (backend_dir / "models.py").write_text(backend.models_code, encoding="utf-8")
        (backend_dir / "__init__.py").write_text("", encoding="utf-8")

        # 5. Tests
        (test_dir / "test_api.py").write_text(qa.test_suite_code, encoding="utf-8")
        (test_dir / "__init__.py").write_text("", encoding="utf-8")

        # 6. pyproject.toml
        pyproject_content = f"""[project]
name = "{proposal.app_name}"
version = "0.1.0"
description = "{proposal.title} powered by Nexus Platform Framework"
requires-python = ">=3.11"
dependencies = [
    "nexus-framework>=0.1.0",
    "uvicorn>=0.30.0",
]

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"
"""
        (app_dir / "backend" / "pyproject.toml").write_text(pyproject_content, encoding="utf-8")

        return app_dir
