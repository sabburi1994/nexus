DEFAULT_SQUAD_BUDGET_USD = 1.00
"""Spend cap for one ``build_from_idea`` run (all agents and healing cycles together)."""


class DeliveredProject(BaseModel):
    """The complete software package generated by the Nexus IT Team."""

    proposal: ProductProposal
    solution: SolutionBlueprint
    data_architecture: DataArchitecture
    ui: UiSpecification
    fullstack: FullStackSpecification
    devops: DevopsSpecification
    qa: QaSpecification
    output_path: str | None = None
    healing_report: SelfHealingReport | None = None
    test_run: TestRunResult | None = None
    qa_passed: bool = False
    cost_usd: float = 0.0
    budget_usd: float = DEFAULT_SQUAD_BUDGET_USD


class NexusITTeam:
    """
    Virtual IT Team of Autonomous Subagents:
    - Business Analyst
    - Solution Architect
    - Data Architect
    - UI/UX Designer
    - Full-Stack Engineer
    - DevOps Engineer (Terraform / IaC)
    - QA & Security Engineer
    - Closed-Loop Self-Healer

    Every model call of a run is recorded in an ``AgentContext``; the run stops with
    ``BudgetExceededError`` once it spends more than ``max_budget_usd``.

    When ``build_from_idea`` writes the workspace to disk and ``run_generated_tests`` is on,
    the generated pytest suite is executed for real (subprocess, timeout) and the result is
    the QA gate that drives self-healing. That runs model generated code on this machine:
    turn it off when the idea or the model output can be steered by someone you do not trust.
    One team instance runs one build at a time.
    """

    def __init__(
        self,
        provider: BaseModelProvider | None = None,
        max_budget_usd: float = DEFAULT_SQUAD_BUDGET_USD,
        run_generated_tests: bool = True,
        test_timeout_s: float = DEFAULT_TEST_TIMEOUT_S,
    ) -> None:
        self.provider = provider or VertexAIProvider()
        self.max_budget_usd = max_budget_usd
        self.run_generated_tests = run_generated_tests
        self.test_timeout_s = test_timeout_s
        self.context = AgentContext(max_budget_usd=max_budget_usd)
        # Agents talk to the budgeted wrapper so every call counts against the cap.
        self._budgeted = BudgetedProvider(self.provider, self.context)
        self.ba = BusinessAnalystAgent(self._budgeted)
        self.solution_architect = SolutionArchitectAgent(self._budgeted)
        self.data_architect = DataArchitectAgent(self._budgeted)
        self.designer = UiDesignerAgent(self._budgeted)
        self.fullstack = FullStackEngineerAgent(self._budgeted)
        self.devops = DevopsEngineerAgent(self._budgeted)
        self.qa = QaEngineerAgent(self._budgeted)
        self.healer = ClosedLoopHealer(self._budgeted)

    def build_from_idea(
        self,
        raw_user_idea: str,
        target_cloud: str = "gcp",
        output_dir: Path | None = None,
        enable_self_healing: bool = True,
        max_healing_cycles: int = 3,
        run_generated_tests: bool | None = None,
    ) -> DeliveredProject:
        """Run the end-to-end squad workflow from idea to deployed architecture.

        ``run_generated_tests`` overrides the team default for this run. Real test execution
        needs ``output_dir``: without a workspace on disk QA falls back to its self reported
        ``passed_preflight``.
        """
        # Fresh spend ledger per run.
        self.context = AgentContext(max_budget_usd=self.max_budget_usd)
        self._budgeted.context = self.context
        run_tests = self.run_generated_tests if run_generated_tests is None else run_generated_tests

        # 1. Business Analyst
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Business Analyst",
                f"Analyzing requirements for: '{raw_user_idea[:60]}...'",
            )
        )
        proposal = self.ba.analyze_requirements(raw_user_idea)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Business Analyst",
                f"Proposal compiled: {proposal.title}",
                {"snippet": proposal.tagline},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Business Analyst",
                f"Delivered {len(proposal.user_stories)} user stories.",
            )
        )

        # 2. Solution Architect
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Solution Architect",
                f"Evaluating system topology and cloud strategy for {target_cloud.upper()}...",
            )
        )
        solution = self.solution_architect.design_solution(proposal, target_cloud=target_cloud)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Solution Architect",
                f"Architecture Blueprint ready ({solution.compute_pattern})",
                {"snippet": solution.system_topology},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Solution Architect",
                f"Target cloud: {solution.cloud_provider.upper()}, services: {len(solution.integration_services)}",
            )
        )

        # 3. Data Architect
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Data Architect",
                f"Designing normalized relational schema & DDL for {proposal.title}...",
            )
        )
        data_arch = self.data_architect.design_data_model(proposal, solution)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Data Architect",
                f"Data Architecture locked ({len(data_arch.tables)} tables)",
                {"snippet": data_arch.database_engine},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Data Architect",
                f"Generated SQL DDL schema with {len(data_arch.indexes)} indexes.",
            )
        )

        # 4. UI/UX Designer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "UI/UX Designer",
                f"Crafting user journey, design tokens & wireframes for {proposal.title}...",
            )
        )
        ui = self.designer.design_ui(proposal, solution)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "UI/UX Designer",
                f"UI mockup ready: {ui.component_name}",
                {"snippet": ui.color_palette},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "UI/UX Designer",
                "UI tokens and visual mockup ready.",
            )
        )

        # 5. Full-Stack Engineer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "Full-Stack Engineer",
                "Implementing unified React frontend + FastAPI backend...",
            )
        )
        fullstack = self.fullstack.build_application(proposal, solution, data_arch, ui)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "Full-Stack Engineer",
                "Full-Stack codebase compiled",
                {"snippet": fullstack.backend_main_py[:120]},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "Full-Stack Engineer",
                "React interface + FastAPI microservice integrated.",
            )
        )

        # 6. DevOps Engineer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "DevOps Engineer",
                f"Generating Terraform (IaC) and container config for {solution.cloud_provider.upper()}...",
            )
        )
        devops = self.devops.build_infrastructure(proposal, solution)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "DevOps Engineer",
                f"Terraform IaC compiled ({solution.cloud_provider})",
                {"snippet": devops.terraform_main_tf[:120]},
            )
        )
        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "DevOps Engineer",
                "Terraform (platform modules), Dockerfile & deploy script ready.",
            )
        )

        # 7. QA & Security Engineer
        event_bus.emit(
            AgentEvent(
                EventType.AGENT_STARTED,
                "QA & Security Engineer",
                "Executing preflight security check & generating test suite...",
            )
        )
        qa = self.qa.verify_and_test(proposal, solution, fullstack)
        event_bus.emit(
            AgentEvent(
                EventType.ARTIFACT_GENERATED,
                "QA & Security Engineer",
                "Automated pytest suite compiled",
                {"snippet": qa.test_suite_code[:120]},
            )
        )
        # Real QA gate: write the workspace and run the generated suite.
        app_dir = output_dir / tpl.service_slug(proposal.app_name) if output_dir else None
        test_runner: TestRunner | None = None
        test_run: TestRunResult | None = None
        if app_dir is not None and run_tests:
            workspace = app_dir

            def write_and_test(fs: FullStackSpecification, q: QaSpecification) -> TestRunResult:
                self._write_to_disk(workspace, proposal, solution, data_arch, ui, fs, devops, q)
                return qa_runner.run_generated_tests(workspace / "backend", timeout_s=self.test_timeout_s)

            test_runner = write_and_test
            test_run = test_runner(fullstack, qa)

        event_bus.emit(
            AgentEvent(
                EventType.STEP_COMPLETED,
                "QA & Security Engineer",
                f"Preflight clearance: {'PASSED' if qa_gate_passed(qa, test_run) else 'WARN'}"
                + (f" ({test_run.summary})" if test_run is not None else " (self reported, tests not executed)"),
            )
        )

        healing_report: SelfHealingReport | None = None
        if enable_self_healing and not qa_gate_passed(qa, test_run):
            self.healer.max_healing_cycles = max_healing_cycles
            fullstack, qa, healing_report = self.healer.run_healing_loop(
                proposal=proposal,
                solution=solution,
                fullstack=fullstack,
                qa=qa,
                fullstack_agent=self.fullstack,
                qa_agent=self.qa,
                test_runner=test_runner,
                initial_test_run=test_run,
            )
            test_run = healing_report.final_test_run

        saved_path = None
        if app_dir is not None:
            saved_path = str(self._write_to_disk(app_dir, proposal, solution, data_arch, ui, fullstack, devops, qa))
            event_bus.emit(
                AgentEvent(
                    EventType.RUN_COMPLETED,
                    "Squad Orchestrator",
                    f"Project delivered to disk at {saved_path}",
                )
            )
        else:
            event_bus.emit(
                AgentEvent(
                    EventType.RUN_COMPLETED,
                    "Squad Orchestrator",
                    "Project delivery complete.",
                )
            )

        return DeliveredProject(
            proposal=proposal,
            solution=solution,
            data_architecture=data_arch,
            ui=ui,
            fullstack=fullstack,
            devops=devops,
            qa=qa,
            output_path=saved_path,
            healing_report=healing_report,
            test_run=test_run,
            qa_passed=qa_gate_passed(qa, test_run),
            cost_usd=self.context.accumulated_cost_usd,
            budget_usd=self.max_budget_usd,
        )

    @staticmethod
    def _sanitize_python(code: str) -> str:
        """Clean a model supplied Python file (fences, prose, escapes, imports); see ``code_normalizer``."""
        return normalize_python(code)

    def _write_to_disk(
        self,
        app_dir: Path,
        proposal: ProductProposal,
        solution: SolutionBlueprint,
        data_arch: DataArchitecture,
        ui: UiSpecification,
        fullstack: FullStackSpecification,
        devops: DevopsSpecification,
        qa: QaSpecification,
    ) -> Path:
        """Write all generated artifacts into a runnable workspace."""
        backend_dir = app_dir / "backend" / "src"
        test_dir = app_dir / "backend" / "tests"
        frontend_dir = app_dir / "frontend" / "src"
        infra_dir = app_dir / "infra" / "terraform"
        docs_dir = app_dir / "docs"
        scripts_dir = app_dir / "scripts"

        for d in (backend_dir, test_dir, frontend_dir, infra_dir, docs_dir, scripts_dir):
            d.mkdir(parents=True, exist_ok=True)

        # 1. Documentation
        (docs_dir / "PROPOSAL.md").write_text(
            f"# {proposal.title}\n\n> {proposal.tagline}\n\n## User Stories\n"
            + "\n".join(f"- {s}" for s in proposal.user_stories),
            encoding="utf-8",
        )
        (docs_dir / "ARCHITECTURE.md").write_text(
            f"# System Architecture Blueprint\n\n- Cloud Target: {solution.cloud_provider}\n- Compute: {solution.compute_pattern}\n\n## Topology\n{solution.system_topology}",
            encoding="utf-8",
        )
        (docs_dir / "DATA_ARCHITECTURE.md").write_text(
            f"# Data Architecture\n\nEngine: {data_arch.database_engine}\n\n## Tables\n"
            + "\n".join(f"- {t}" for t in data_arch.tables)
            + f"\n\n## SQL Schema\n```sql\n{data_arch.sql_ddl_schema}\n```",
            encoding="utf-8",
        )
        (docs_dir / "preview_mockup.html").write_text(proposal.wireframe_preview_html, encoding="utf-8")

        # 2. Frontend
        (frontend_dir / "App.tsx").write_text(normalize_source(fullstack.frontend_app_tsx), encoding="utf-8")
        (frontend_dir / "api.ts").write_text(normalize_source(fullstack.frontend_api_client_ts), encoding="utf-8")
        for rel_path, content in tpl.render_frontend_files(proposal.app_name, proposal.title).items():
            dest = app_dir / "frontend" / rel_path
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")

        # 3. Backend
        (backend_dir / "main.py").write_text(self._sanitize_python(fullstack.backend_main_py), encoding="utf-8")
        sanitized_models = self._sanitize_python(fullstack.backend_models_py)
        (backend_dir / "models.py").write_text(sanitized_models, encoding="utf-8")
        (backend_dir / "backend_models.py").write_text(sanitized_models, encoding="utf-8")
        (backend_dir / "__init__.py").write_text("", encoding="utf-8")

        # 4. Tests
        (test_dir / "test_api.py").write_text(self._sanitize_python(qa.test_suite_code), encoding="utf-8")
        (test_dir / "__init__.py").write_text("", encoding="utf-8")

        # 5. Container, Infrastructure as Code (Terraform) and deploy script
        backend_root = app_dir / "backend"
        (backend_root / "Dockerfile").write_text(
            normalize_source(devops.dockerfile) or tpl.render_dockerfile(), encoding="utf-8"
        )
        (backend_root / ".dockerignore").write_text(tpl.render_dockerignore(), encoding="utf-8")
        (backend_root / "requirements.txt").write_text(tpl.render_backend_requirements(), encoding="utf-8")
        (infra_dir / "main.tf").write_text(normalize_source(devops.terraform_main_tf), encoding="utf-8")
        (infra_dir / "variables.tf").write_text(normalize_source(devops.terraform_variables_tf), encoding="utf-8")
        (app_dir / "docker-compose.yml").write_text(normalize_source(devops.docker_compose_yml), encoding="utf-8")
        deploy_script = scripts_dir / "deploy.sh"
        # newline="\n": the script keeps LF line endings even when generated on Windows.
        deploy_script.write_text(
            normalize_source(devops.deploy_script_sh) or tpl.render_deploy_script(proposal.app_name),
            encoding="utf-8",
            newline="\n",
        )
        deploy_script.chmod(0o755)

        # 6. pyproject.toml
        (backend_root / "pyproject.toml").write_text(
            tpl.render_backend_pyproject(proposal.app_name, proposal.title), encoding="utf-8"
        )

        return app_dir
