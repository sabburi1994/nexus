"""Nexus IT Pack: Engineering Manager Agent."""
from __future__ import annotations

from pydantic import BaseModel, Field
from nexus.providers.base import BaseModelProvider
from nexus.teams.it_pack.ba import ProductProposal


class EngineeringTask(BaseModel):
    """An actionable task assigned to an IT squad member."""
    task_id: str = Field(description="e.g. TASK-1")
    title: str = Field(description="Task title")
    assignee: str = Field(description="Assigned role: 'Frontend Designer', 'Backend Engineer', or 'QA & Security'")
    description: str = Field(description="Technical implementation details")


class SprintPlan(BaseModel):
    """Structured sprint plan generated by the Engineering Manager."""
    architecture_overview: str = Field(description="High-level tech stack and architecture")
    database_entities: list[str] = Field(description="Key database models and relationships")
    api_endpoints: list[str] = Field(description="Primary REST endpoints: [METHOD] /path - description")
    tasks: list[EngineeringTask] = Field(description="Chronological engineering tasks")
    estimated_tokens_needed: int = Field(description="Estimated LLM token budget")


class EngineeringManagerAgent:
    """
    Engineering Manager Agent in the Nexus Core IT Pack.
    Reviews the BA's product proposal and generates a comprehensive technical architecture and task breakdown.
    """

    def __init__(self, provider: BaseModelProvider) -> None:
        self.provider = provider

    def plan_sprint(self, proposal: ProductProposal) -> SprintPlan:
        """Create a full technical sprint plan from the BA's proposal."""
        prompt = f"""You are the Engineering Manager & Principal Architect of an IT team.
Review the following Product Proposal from our Business Analyst:
App: {proposal.title} ({proposal.app_name})
Tagline: {proposal.tagline}
Features: {', '.join(proposal.core_features)}
User Stories: {', '.join(proposal.user_stories)}

Create the technical architecture and sprint plan:
1. Define the backend architecture using Nexus Framework (FastAPI, PostgreSQL async, Gemini 3.8).
2. List the database entities.
3. List the REST API endpoints.
4. Break down work into distinct tasks for the Designer, Backend Engineer, and QA Engineer.
"""
        system = "You are a pragmatic, meticulous Engineering Manager."
        return self.provider.structured(prompt, SprintPlan, system_instruction=system)
